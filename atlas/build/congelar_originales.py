"""Task 2.1: copy the originals listed in atlas/INVENTARIO.csv to atlas/source-data/originales/,
keeping their path relative to Mapas/, and write MANIFEST.csv with verified sha256.
Only reads the originals. Excludes chats, .libs, hosting.json and the forbidden UI scripts (PLAN §6.1, P6).
Usage: python3.12 -I congelar_originales.py"""
import csv, hashlib, shutil
from pathlib import Path

ATLAS = Path(__file__).resolve().parents[1]
MAPAS = ATLAS.parents[1]
DEST = ATLAS / 'source-data' / 'originales'
STATES = {'original-vectorial', 'original-render', 'original-vista', 'licencia', 'documentacion', 'herramienta'}
# atlas-escenarios generators are needed to port texts and frame rules; refine_ui/finish_ui are excluded by state.
APP_TOOLS = {'atlas-escenarios/scripts/build_data.py', 'atlas-escenarios/scripts/build_extension.py',
             'atlas-escenarios/scripts/extension_complementos.py', 'atlas-escenarios/scripts/extract_original.py'}

def sha(p): return hashlib.sha256(p.read_bytes()).hexdigest()

rows = list(csv.DictReader(open(ATLAS / 'INVENTARIO.csv', encoding='utf-8-sig')))
# mapa-datos.js is generated by the prospective generator, but it is the data of the original view (cases + NE base).
EXTRA = {'mapas/fronteras-2100/mapa-datos.js'}
picked = [r for r in rows if (r['estado'] in STATES and (r['ruta'].startswith('mapas/') or r['ruta'] in APP_TOOLS)) or r['ruta'] in EXTRA]
out = []
for r in picked:
    src = MAPAS / r['ruta']
    assert '.libs' not in src.parts and 'chats' not in src.parts and src.name != 'hosting.json', src
    h = sha(src)
    assert h == r['sha256'], f'{r["ruta"]}: el original cambió desde el inventario'
    dst = DEST / r['ruta']
    dst.parent.mkdir(parents=True, exist_ok=True)
    if not dst.exists() or sha(dst) != h:
        shutil.copy2(src, dst)
    assert sha(dst) == h, dst
    out.append(dict(origen=r['ruta'], copia=dst.relative_to(ATLAS).as_posix(), bytes=src.stat().st_size,
                    sha256=h, estado=r['estado'], mapa=r['mapa']))
with open(DEST / 'MANIFEST.csv', 'w', encoding='utf-8', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(out[0]), lineterminator='\n')
    w.writeheader(); w.writerows(out)
print(len(out), 'ficheros copiados y verificados;', sum(o['bytes'] for o in out), 'bytes')
